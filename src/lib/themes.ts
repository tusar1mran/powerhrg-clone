export function themeScript() {
  const map = Object.fromEntries(themes.map((t) => [t.id, t.colors]));
  return `try{var m=${JSON.stringify(map)};var t=m[localStorage.getItem(${JSON.stringify(themeStorageKey)})];if(t){var s=document.documentElement.style;for(var k in t)s.setProperty("--color-"+k,t[k]);}}catch(e){}`;
}
